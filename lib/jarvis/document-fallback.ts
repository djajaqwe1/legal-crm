/** Структурный черновик, если LLM недоступен или таймаут на проде. */

export function buildFallbackDocument(
  type: string,
  clientName: string,
  situation: string,
  caseTitle?: string,
): string {
  const today = new Date().toLocaleDateString("ru-RU");
  const body = situation.trim().slice(0, 1200);
  const title = caseTitle?.trim() || "Дело";

  if (/претенз/i.test(type)) {
    return `ПРЕТЕЗИЯ (досудебное требование)

Кому: [ЗАПОЛНИТЬ — наименование / ФИО контрагента]
Адрес: [ЗАПОЛНИТЬ]

От: ${clientName}
Дело: ${title}

${today}

Уважаемый(ая) [ЗАПОЛНИТЬ]!

${body}

На основании изложенного ТРЕБУЮ:
1. [ЗАПОЛНИТЬ — суть требования: устранить нарушение / оплатить / выполнить работы]
2. Предоставить письменный ответ в срок 10 (десять) календарных дней с даты получения настоящей претензии.

В случае неудовлетворения требований в указанный срок ${clientName} оставляет за собой право обратиться в суд для защиты нарушенных прав и законных интересов, а также взыскания неустойки, убытков и судебных расходов.

Приложения:
1. Документы, подтверждающие обстоятельства дела.

Документ подготовлен юридической службой ТОО «Конгломерат Алтай» от имени ${clientName}.

_________________ / [ФИО представителя] /`;
  }

  if (/иск/i.test(type)) {
    return `ИСКОВОЕ ЗАЯВЛЕНИЕ (черновик)

В [ЗАПОЛНИТЬ — суд]
Истец: ${clientName}
Ответчик: [ЗАПОЛНИТЬ]
Дело: ${title}

${today}

${body}

ПРОШУ СУД:
1. [ЗАПОЛНИТЬ — просительная часть]

Приложения: [ЗАПОЛНИТЬ]

Подготовлено ТОО «Конгломерат Алтай».`;
  }

  return `${type.toUpperCase()} (черновик)

Клиент: ${clientName}
Дело: ${title}
Дата: ${today}

${body}

[ЗАПОЛНИТЬ — завершить документ]

ТОО «Конгломерат Алтай»`;
}
